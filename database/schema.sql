-- ============================================================
--  공통 : MEMBER (회원)
--  * 이미 생성되어 있다면 이 블록은 건너뛰세요.
--    (server/login.js 가 사용하는 컬럼과 동일하게 맞춰 둠)
-- ============================================================
CREATE TABLE MEMBER (
  USER_ID        VARCHAR2(50)   PRIMARY KEY,          -- 아이디(로그인)
  USER_PASSWORD  VARCHAR2(200)  NOT NULL,             -- 비밀번호
  USER_NAME      VARCHAR2(50)   NOT NULL,             -- 이름
  EMAIL          VARCHAR2(100),                       -- 이메일
  CREATED_AT     TIMESTAMP      DEFAULT SYSTIMESTAMP  -- 가입 시간
);


-- ============================================================
--  [슬라이드 1] 여행지 상세 · 비교 화면
-- ============================================================

-- 여행지 (협재해변 같은 대표 장소)
CREATE TABLE PLACE (
  PLACE_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NAME              VARCHAR2(100) NOT NULL,   -- 협재해변
  REGION            VARCHAR2(50),             -- 제주특별자치도
  CITY              VARCHAR2(50),             -- 제주시
  SUMMARY           VARCHAR2(300),            -- 한 줄 소개
  DESCRIPTION       CLOB,                     -- 상세 소개 본문(긴 글)
  OPEN_TIME         VARCHAR2(100),            -- 운영시간 (연중무휴 00:00~24:00)
  FEE               VARCHAR2(100),            -- 이용요금 (무료)
  LOCATION          VARCHAR2(200),            -- 위치 (제주시 한림읍 협재리)
  ADDRESS           VARCHAR2(200),            -- 주소
  PUBLIC_TRANSPORT  VARCHAR2(200),            -- 대중교통 안내
  CAR_INFO          VARCHAR2(200),            -- 자가용 안내
  RECOMMEND_SEASON  VARCHAR2(100),            -- 추천 계절 (봄,여름,가을)
  RECOMMEND_TIME    VARCHAR2(100),            -- 추천 시간대 (일몰 시간)
  TRAVEL_STYLE      VARCHAR2(100),            -- 여행 스타일 (가족·커플여행)
  KEYWORD           VARCHAR2(200),            -- 키워드 (에메랄드빛·노을·비양도)
  MAP_X             NUMBER(10,7),             -- 지도 좌표(위도)
  MAP_Y             NUMBER(10,7),             -- 지도 좌표(경도)
  CREATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP
);

-- 여행지 사진 (화면의 1/12 사진 슬라이드)
CREATE TABLE PLACE_IMAGE (
  IMAGE_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PLACE_ID    NUMBER        NOT NULL,   -- 어느 여행지 사진인지
  IMAGE_URL   VARCHAR2(500) NOT NULL,   -- 사진 경로
  SORT_ORDER  NUMBER        DEFAULT 0,  -- 사진 순서
  CONSTRAINT FK_PLACE_IMAGE_PLACE
    FOREIGN KEY (PLACE_ID) REFERENCES PLACE(PLACE_ID)
);

-- 주변 추천 장소 (맛집 / 숙소 / 축제·행사 / 가볼만한 곳)
CREATE TABLE NEARBY_PLACE (
  NEARBY_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PLACE_ID     NUMBER        NOT NULL,  -- 어느 여행지 주변인지
  CATEGORY     VARCHAR2(30),            -- 맛집/숙소/축제·행사/가볼만한 곳
  NAME         VARCHAR2(100) NOT NULL,  -- 협재 해녀의 집
  DESCRIPTION  VARCHAR2(300),           -- 제주 향토 해산물 요리
  LOCATION     VARCHAR2(200),           -- 제주시 한림읍
  IMAGE_URL    VARCHAR2(500),           -- 사진 경로
  CONSTRAINT FK_NEARBY_PLACE_PLACE
    FOREIGN KEY (PLACE_ID) REFERENCES PLACE(PLACE_ID)
);

-- 저장한 여행지 (♡ 저장하기 / 즐겨찾기)
CREATE TABLE SAVED_PLACE (
  SAVE_ID   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USER_ID   VARCHAR2(50) NOT NULL,              -- 누가 저장했는지
  PLACE_ID  NUMBER       NOT NULL,              -- 저장한 여행지
  SAVED_AT  TIMESTAMP    DEFAULT SYSTIMESTAMP,  -- 저장 시간
  CONSTRAINT FK_SAVED_PLACE_MEMBER
    FOREIGN KEY (USER_ID)  REFERENCES MEMBER(USER_ID),
  CONSTRAINT FK_SAVED_PLACE_PLACE
    FOREIGN KEY (PLACE_ID) REFERENCES PLACE(PLACE_ID),
  CONSTRAINT UQ_SAVED_PLACE UNIQUE (USER_ID, PLACE_ID)  -- 같은 여행지 중복 저장 방지
);


-- ============================================================
--  [슬라이드 2] AI 여행 일정 만들기 화면
-- ============================================================

-- 여행 일정 (왼쪽 입력 조건 + 일정 묶음)
CREATE TABLE ITINERARY (
  ITINERARY_ID  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USER_ID       VARCHAR2(50) NOT NULL,   -- 누구의 일정인지
  TITLE         VARCHAR2(200),           -- 2박 3일 제주 여행 일정
  START_DATE    DATE,                    -- 여행 시작일
  END_DATE      DATE,                    -- 여행 종료일
  DESTINATION   VARCHAR2(100),           -- 여행지 (제주)
  BUDGET        NUMBER,                  -- 예산 (원)
  PEOPLE_COUNT  NUMBER,                  -- 여행 인원
  TRANSPORT     VARCHAR2(50),            -- 이동 수단 (자차)
  TRAVEL_STYLE  VARCHAR2(100),           -- 여행 스타일 (자연·힐링)
  CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT FK_ITINERARY_MEMBER
    FOREIGN KEY (USER_ID) REFERENCES MEMBER(USER_ID)
);

-- 일정 상세 (1일차·2일차 시간표의 한 줄 한 줄)
CREATE TABLE ITINERARY_ITEM (
  ITEM_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ITINERARY_ID  NUMBER        NOT NULL,  -- 어느 일정에 속하는지
  DAY_NO        NUMBER,                  -- 1일차 / 2일차 / 3일차
  ITEM_DATE     DATE,                    -- 날짜
  ITEM_TIME     VARCHAR2(10),            -- 시간 (08:00)
  CATEGORY      VARCHAR2(30),            -- 아침식사/관광/점심식사/축제·이벤트/숙소체크인
  PLACE_NAME    VARCHAR2(100),           -- 제주 고기국수
  DESCRIPTION   VARCHAR2(500),           -- 항목 설명
  LOCATION      VARCHAR2(200),           -- 제주시 연동
  DURATION      VARCHAR2(50),            -- 소요 시간 (1시간)
  SORT_ORDER    NUMBER        DEFAULT 0, -- 순서(순서 바꾸기 기능용)
  MAP_X         NUMBER(10,7),            -- 경로 지도 좌표(위도)
  MAP_Y         NUMBER(10,7),            -- 경로 지도 좌표(경도)
  CONSTRAINT FK_ITINERARY_ITEM
    FOREIGN KEY (ITINERARY_ID) REFERENCES ITINERARY(ITINERARY_ID)
);

-- AI 여행 도우미 (오른쪽 아래 챗봇 질문/답변)
CREATE TABLE AI_CHAT (
  CHAT_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ITINERARY_ID  NUMBER,                  -- 어느 일정에서 물어본 질문인지
  QUESTION      VARCHAR2(1000),          -- 제주도 10월 날씨는 어떤가요?
  ANSWER        CLOB,                    -- AI 답변(긴 글)
  CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT FK_AI_CHAT_ITINERARY
    FOREIGN KEY (ITINERARY_ID) REFERENCES ITINERARY(ITINERARY_ID)
);

-- 참고 관광자료 (AI 답변 아래의 출처 링크들)
CREATE TABLE AI_CHAT_SOURCE (
  SOURCE_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CHAT_ID      NUMBER        NOT NULL,   -- 어느 답변의 출처인지
  SOURCE_NAME  VARCHAR2(200),           -- 제주특별자치도 관광정보
  SOURCE_URL   VARCHAR2(500),           -- 링크 주소
  CONSTRAINT FK_AI_CHAT_SOURCE
    FOREIGN KEY (CHAT_ID) REFERENCES AI_CHAT(CHAT_ID)
);


-- ============================================================
--  [슬라이드 3] 교통 · 숙소 비교 화면
-- ============================================================

-- 교통 정보 (버스 / 기차 / 항공 / 자차 비교 목록)
CREATE TABLE TRANSPORT (
  TRANSPORT_ID  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TYPE          VARCHAR2(20),   -- 버스 / 기차 / 항공 / 자차
  COMPANY       VARCHAR2(100),  -- 고속버스(프리미엄) / KTX / 진에어
  FROM_CITY     VARCHAR2(50),   -- 출발 도시 (서울)
  TO_CITY       VARCHAR2(50),   -- 도착 도시 (부산)
  DEPARTURE     VARCHAR2(100),  -- 출발지 (서울경부터미널)
  ARRIVAL       VARCHAR2(100),  -- 도착지 (부산종합터미널)
  DEPART_TIME   VARCHAR2(10),   -- 출발 시간 (06:30)
  ARRIVE_TIME   VARCHAR2(10),   -- 도착 시간 (10:55)
  DURATION      VARCHAR2(50),   -- 소요 시간 (4시간 25분)
  PRICE         NUMBER,         -- 요금 (28600)
  TAG           VARCHAR2(50),   -- 최저가 / 최단 시간
  SOURCE        VARCHAR2(100),  -- 출처 (코버스/코레일/스카이스캐너)
  UPDATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP  -- 최종 업데이트
);

-- 숙소 정보 (부산 인기 숙소 비교)
CREATE TABLE ACCOMMODATION (
  ACCOM_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NAME          VARCHAR2(100) NOT NULL,  -- 부산 광안리 오션뷰 호텔
  CITY          VARCHAR2(50),            -- 지역 (부산)
  RATING        NUMBER(2,1),             -- 평점 (4.7)
  REVIEW_COUNT  NUMBER,                  -- 리뷰 수 (832)
  ADDRESS       VARCHAR2(200),           -- 부산 수영구 광안해변로 219
  DESCRIPTION   VARCHAR2(300),           -- 숙소 설명
  PRICE         NUMBER,                  -- 1박 가격 (120000)
  SOURCE        VARCHAR2(100),           -- 출처 (야놀자/아고다)
  MAP_X         NUMBER(10,7),            -- 지도 좌표(위도)
  MAP_Y         NUMBER(10,7),            -- 지도 좌표(경도)
  UPDATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP
);

-- 숙소 편의시설 태그 (오션뷰 · 무료 Wi-Fi · 조식 포함 · 주차 가능)
CREATE TABLE ACCOMMODATION_AMENITY (
  AMENITY_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ACCOM_ID      NUMBER       NOT NULL,   -- 어느 숙소의 시설인지
  AMENITY_NAME  VARCHAR2(50),           -- 오션뷰 / 무료 Wi-Fi / 조식 포함 / 주차 가능
  CONSTRAINT FK_ACCOM_AMENITY
    FOREIGN KEY (ACCOM_ID) REFERENCES ACCOMMODATION(ACCOM_ID)
);

