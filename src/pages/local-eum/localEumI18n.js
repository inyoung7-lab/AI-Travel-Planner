export function normalizeLocalEumLocale(locale) {
  return SUPPORTED_LOCALES.includes(locale) ? locale : 'ko';
}

export function translate(locale, key, params = {}) {
  const normalizedLocale = normalizeLocalEumLocale(locale);
  const template = MESSAGES[normalizedLocale][key] ?? MESSAGES.ko[key] ?? key;
  return String(template).replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name) => (
    Object.hasOwn(params, name) ? String(params[name]) : match
  ));
}

export function localizedField(record, field, locale) {
  if (!record || typeof field !== 'string') return '';
  const normalizedLocale = normalizeLocalEumLocale(locale);
  if (normalizedLocale !== 'ko') {
    const translated = record.translations?.[normalizedLocale]?.[field];
    if (typeof translated === 'string' && translated.trim()) return translated;
    if (Array.isArray(translated) && translated.length > 0) return translated;
  }
  const source = record[field];
  return source ?? '';
}

export function hasLocalizedField(record, field, locale) {
  if (normalizeLocalEumLocale(locale) === 'ko') return true;
  const value = record?.translations?.[normalizeLocalEumLocale(locale)]?.[field];
  return (typeof value === 'string' && value.trim().length > 0) || (Array.isArray(value) && value.length > 0);
}
