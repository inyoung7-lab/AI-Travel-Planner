$$;
create function public.travel_search_places(p_query text) returns jsonb language sql stable security invoker set search_path='' as $$
 select coalesce(jsonb_agg(x),'[]'::jsonb) from(select place_id id,name,coalesce(address,'') addr,coalesce(region,'') region from public.comm_place
 where position(lower(p_query) in lower(name||' '||coalesce(address,'')))>0 order by place_id limit 8)x;
$$;
create function public.travel_hot_places() returns jsonb language sql stable security invoker set search_path='' as $$
 select coalesce(jsonb_agg(x),'[]'::jsonb) from(select row_number() over(order by count(*) desc,pp.place_id) rank,pp.place_id "placeId",max(p.region) region,count(*) count
 from public.comm_post p join public.comm_post_place pp using(post_id) where p.category='리뷰' and p.created_at>=date_trunc('month',now() at time zone 'Asia/Seoul') at time zone 'Asia/Seoul'
 group by pp.place_id order by count(*) desc,pp.place_id limit 5)x;
$$;
create function public.travel_post_counts() returns jsonb language sql stable security invoker set search_path='' as $$
 select jsonb_build_object('total',count(*),'review',count(*) filter(where category='리뷰'),'trip',count(*) filter(where category='리뷰' and sub_category='여행 리뷰'),
 'place',count(*) filter(where category='리뷰' and sub_category='장소 리뷰'),'question',count(*) filter(where category='질문'),'talk',count(*) filter(where category='소통'),
 'regions',coalesce((select jsonb_object_agg(region,cnt) from(select region,count(*) cnt from public.comm_post where region is not null group by region)r),'{}'::jsonb)) from public.comm_post;
$$;
create function public.travel_itinerary_regions() returns jsonb language sql stable security invoker set search_path='' as $$
 select coalesce(jsonb_agg(region),'[]'::jsonb) from(select region from public.comm_place where region is not null and(ext_key ~ '^tourapi:[0-9]+$' or ext_key like 'sample:%') group by region having count(*)>=3 order by region)x;
$$;
-- Explicit RPC grants: PostgreSQL otherwise grants function execution to PUBLIC.
do $$ declare f record;begin
 for f in select p.oid::regprocedure signature,p.proname from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.proname like 'travel_%' loop
 execute format('revoke all on function %s from public,anon,authenticated',f.signature);
 if f.proname in ('travel_view_post','travel_author_trip_count','travel_search_places','travel_hot_places','travel_post_counts','travel_itinerary_regions') then
 execute format('grant execute on function %s to anon,authenticated',f.signature);
 elsif f.proname not in ('travel_sync_profile','travel_like_counter','travel_check_comment_parent') then
 execute format('grant execute on function %s to authenticated',f.signature);end if;
 end loop;end $$;
