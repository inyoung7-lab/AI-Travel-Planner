create view public.community_posts with(security_invoker=true) as
 select p.*,m.user_name,
 (select count(*)::integer from public.comm_comment c where c.post_id=p.post_id) comment_count,
 (select count(*)::integer from public.comm_comment c where c.post_id=p.post_id and c.parent_id is null) answer_count,
 (select count(*)::integer from public.comm_post_image i where i.post_id=p.post_id) photo_count,
 coalesce((select jsonb_agg(pp.place_id order by pp.pp_id) from public.comm_post_place pp where pp.post_id=p.post_id),'[]'::jsonb) place_ids,
 coalesce((select jsonb_object_agg(pp.place_id,pp.rating) from public.comm_post_place pp where pp.post_id=p.post_id and pp.rating is not null),'{}'::jsonb) place_ratings,
 (select left(c.content,100) from public.comm_comment c where c.post_id=p.post_id and c.parent_id is null order by c.like_count desc,c.created_at limit 1) top_answer,
 p.title||' '||p.content||' '||coalesce((select string_agg(cp.name||' '||coalesce(cp.address,''),' ') from public.comm_post_place pp join public.comm_place cp using(place_id) where pp.post_id=p.post_id),'') search_text
 from public.comm_post p join public.travel_profiles m using(user_id);
create view public.community_comments with(security_invoker=true) as
 select c.*,m.user_name from public.comm_comment c join public.travel_profiles m using(user_id);
create view public.community_place_reviews with(security_invoker=true) as
 select p.post_id,p.content,p.like_count,p.created_at,p.user_name,p.photo_count,pp.place_id,coalesce(pp.rating,p.rating) rating
 from public.community_posts p join public.comm_post_place pp using(post_id) where p.category='리뷰';
grant select on public.community_posts,public.community_comments,public.community_place_reviews to anon,authenticated;

create function public.travel_create_post(p_category text,p_sub_category text,p_title text,p_content text,p_region text,p_place_ids bigint[],p_ratings jsonb)
 returns bigint language plpgsql security invoker set search_path='' as $$
declare v_id bigint;begin
 if auth.uid() is null then raise insufficient_privilege;end if;
 if cardinality(p_place_ids)>10 or (p_category='리뷰' and cardinality(p_place_ids)=0) then raise check_violation;end if;
 insert into public.comm_post(user_id,category,sub_category,title,content,region) values(auth.uid(),p_category,p_sub_category,p_title,p_content,p_region) returning post_id into v_id;
 insert into public.comm_post_place(post_id,place_id,rating)
 select v_id,x,nullif(p_ratings->>x::text,'')::integer from unnest(p_place_ids) x;
 return v_id;end $$;
create function public.travel_save_place(p_name text,p_address text,p_region text,p_lat double precision,p_lng double precision,p_ext_key text)
 returns bigint language plpgsql security invoker set search_path='' as $$
declare v_id bigint;begin
 if auth.uid() is null then raise insufficient_privilege;end if;
 perform pg_advisory_xact_lock(hashtextextended('place:'||p_ext_key,0));
 select place_id into v_id from public.comm_place where ext_key=p_ext_key;
 if v_id is null then
 insert into public.comm_place(name,address,region,lat,lng,ext_key) values(p_name,p_address,p_region,p_lat,p_lng,p_ext_key) returning place_id into v_id;end if;
 return v_id;end $$;
create function public.travel_toggle_like(p_kind text,p_id bigint) returns jsonb language plpgsql security invoker set search_path='' as $$
declare v_liked boolean;v_count integer;begin
 if auth.uid() is null then raise insufficient_privilege;end if;
 perform pg_advisory_xact_lock(hashtextextended('like:'||p_kind||':'||p_id::text,0));
 if p_kind='post' then
 if not exists(select 1 from public.comm_post where post_id=p_id) then raise no_data_found;end if;
 delete from public.comm_post_like where post_id=p_id and user_id=auth.uid();v_liked:=not found;
 if v_liked then insert into public.comm_post_like values(p_id,auth.uid());end if;
 select like_count into v_count from public.comm_post where post_id=p_id;
 elsif p_kind='comment' then
 if not exists(select 1 from public.comm_comment where comment_id=p_id) then raise no_data_found;end if;
 delete from public.comm_comment_like where comment_id=p_id and user_id=auth.uid();v_liked:=not found;
 if v_liked then insert into public.comm_comment_like values(p_id,auth.uid());end if;
 select like_count into v_count from public.comm_comment where comment_id=p_id;
 else raise check_violation;end if;
 return jsonb_build_object('liked',v_liked,'likes',v_count);end $$;
-- Counter writes are confined to triggers, never supplied by API clients.
create function public.travel_like_counter() returns trigger language plpgsql security definer set search_path='' as $$
declare delta integer:=case when TG_OP='INSERT' then 1 else -1 end;begin
 if TG_TABLE_NAME='comm_post_like' then
 update public.comm_post set like_count=greatest(like_count+delta,0) where post_id=coalesce(new.post_id,old.post_id);
 else update public.comm_comment set like_count=greatest(like_count+delta,0) where comment_id=coalesce(new.comment_id,old.comment_id);end if;
 return null;end $$;
revoke all on function public.travel_like_counter() from public;
create trigger travel_post_like_counter after insert or delete on public.comm_post_like for each row execute function public.travel_like_counter();
create trigger travel_comment_like_counter after insert or delete on public.comm_comment_like for each row execute function public.travel_like_counter();
create function public.travel_toggle_wish(p_place_id bigint) returns boolean language plpgsql security invoker set search_path='' as $$
begin
 if auth.uid() is null then raise insufficient_privilege;end if;
 perform pg_advisory_xact_lock(hashtextextended('wish:'||auth.uid()::text||':'||p_place_id::text,0));
 delete from public.mytrip_wish where user_id=auth.uid() and place_id=p_place_id;
 if found then return false;end if;
 insert into public.mytrip_wish(user_id,place_id) values(auth.uid(),p_place_id);return true;end $$;
create function public.travel_add_trip_place(p_trip_id bigint,p_place_id bigint) returns void language plpgsql security invoker set search_path='' as $$
begin
 if auth.uid() is null then raise insufficient_privilege;end if;
 perform pg_advisory_xact_lock(hashtextextended('trip:'||p_trip_id::text,0));
 if not exists(select 1 from public.mytrip_plan where trip_id=p_trip_id and user_id=auth.uid()) then raise no_data_found;end if;
 insert into public.mytrip_place(trip_id,place_id,day_no) select p_trip_id,p_place_id,coalesce(max(day_no),1) from public.mytrip_place where trip_id=p_trip_id;
end $$;
