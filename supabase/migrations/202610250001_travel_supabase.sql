create function public.travel_sync_profile() returns trigger language plpgsql security definer set search_path = '' as $$
begin
 insert into public.travel_profiles(user_id,user_name) values(new.id, coalesce(nullif(left(new.raw_user_meta_data->>'name',100),''),split_part(new.email,'@',1),'여행자'))
 on conflict(user_id) do update set user_name=excluded.user_name;
 return new;
end $$;
revoke all on function public.travel_sync_profile() from public;
create trigger travel_auth_profile after insert or update of raw_user_meta_data,email on auth.users for each row execute function public.travel_sync_profile();
insert into public.travel_profiles(user_id,user_name)
 select id,coalesce(nullif(left(raw_user_meta_data->>'name',100),''),split_part(email,'@',1),'여행자') from auth.users on conflict do nothing;

