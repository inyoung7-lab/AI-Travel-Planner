create function lc_private.lc_valid_detail_list(_items text[])
returns boolean language sql immutable set search_path = ''
as $$
  select cardinality(_items) <= 30
    and coalesce(array_ndims(_items), 1) = 1
    and not exists (
      select 1 from unnest(_items) as item(value)
      where value is null or char_length(btrim(value)) not between 1 and 500
    );
$$;
revoke all on function lc_private.lc_valid_detail_list(text[]) from public, anon, authenticated;
grant execute on function lc_private.lc_valid_detail_list(text[]) to authenticated;

