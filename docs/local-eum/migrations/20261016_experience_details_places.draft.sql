-- Table Editor 등에서 일정표만 바꾸어도 체험의 동시 수정 감지에 반영한다.
create function lc_private.lc_touch_experience_from_steps()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  if tg_op = 'DELETE' then
    update public.lc_experiences set updated_at = now() where experience_id = old.experience_id;
  else
    update public.lc_experiences set updated_at = now() where experience_id = new.experience_id;
    if tg_op = 'UPDATE' and old.experience_id <> new.experience_id then
      update public.lc_experiences set updated_at = now() where experience_id = old.experience_id;
    end if;
  end if;
  return null;
end;
$$;
revoke all on function lc_private.lc_touch_experience_from_steps() from public, anon, authenticated;
create trigger lc_steps_touch_experience after insert or update or delete on public.lc_experience_steps
for each row execute function lc_private.lc_touch_experience_from_steps();

-- confirmed_at은 클라이언트가 지정할 수 없으며 명시 확인 시각을 DB가 기록한다.
create function lc_private.lc_stamp_place_confirmation()
returns trigger language plpgsql set search_path = ''
as $$
begin
  if not new.is_confirmed then
    new.confirmed_at := null;
  elsif tg_op = 'INSERT' then
    new.confirmed_at := now();
  elsif not old.is_confirmed or
    row(new.place_name, new.road_address, new.address_detail, new.latitude, new.longitude,
        new.coordinate_source, new.source_reference, new.map_url)
    is distinct from
    row(old.place_name, old.road_address, old.address_detail, old.latitude, old.longitude,
        old.coordinate_source, old.source_reference, old.map_url) then
    new.confirmed_at := now();
  else
    new.confirmed_at := old.confirmed_at;
  end if;
  return new;
end;
$$;
revoke all on function lc_private.lc_stamp_place_confirmation() from public, anon, authenticated;
create trigger lc_places_stamp_confirmation before insert or update on public.lc_places
for each row execute function lc_private.lc_stamp_place_confirmation();

-- FK만으로 검사할 수 없는 회차→체험→장소의 호스트 일치를 DB에서 검사한다.
create function lc_private.lc_check_session_place_owner()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  if new.meeting_place_id is not null and not exists (
    select 1 from public.lc_places p
    join public.lc_experiences e on e.host_id = p.owner_host_id
    where p.place_id = new.meeting_place_id and e.experience_id = new.experience_id
  ) then
    raise exception 'Meeting place must belong to the experience host' using errcode = '23514';
  end if;
  return new;
end;
$$;
revoke all on function lc_private.lc_check_session_place_owner() from public, anon, authenticated;
create trigger lc_sessions_check_place_owner
before insert or update of meeting_place_id, experience_id on public.lc_sessions
for each row execute function lc_private.lc_check_session_place_owner();

create function lc_private.lc_can_manage_place_host(_host_id bigint)
returns boolean language sql stable security definer set search_path = ''
as $$
  select lc_private.lc_has_role('ADMIN') or exists (
    select 1 from public.lc_hosts h
    where h.host_id = _host_id and h.approval_status = 'APPROVED'
      and lc_private.lc_owns_host(h.host_id)
  );
$$;

-- SECURITY DEFINER로 장소→체험→장소의 RLS 재귀를 피한다. 데이터 변경 기능은 없다.
create function lc_private.lc_is_public_place(_place_id bigint)
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.lc_places p
    where p.place_id = _place_id and p.is_confirmed and (
      exists (
        select 1 from public.lc_experiences e
        where e.venue_place_id = p.place_id
          and lc_private.lc_is_public_experience(e.experience_id)
      ) or exists (
        select 1 from public.lc_sessions s
        where s.meeting_place_id = p.place_id and s.status = 'RECRUITING'
          and lc_private.lc_is_public_experience(s.experience_id)
      )
    )
  );
$$;

