create table public.lc_places (
  place_id bigint generated by default as identity primary key,
  owner_host_id bigint not null references public.lc_hosts(host_id) on delete restrict,
  place_name text not null check (char_length(btrim(place_name)) between 1 and 200),
  road_address text check (char_length(btrim(road_address)) between 1 and 500),
  address_detail text check (char_length(address_detail) <= 200),
  latitude numeric(10,7) check (latitude between -90 and 90),
  longitude numeric(10,7) check (longitude between -180 and 180),
  directions text check (char_length(directions) <= 4000),
  map_provider text not null default 'KAKAO' check (map_provider in ('KAKAO', 'NAVER')),
  provider_place_id text check (char_length(btrim(provider_place_id)) between 1 and 200),
  map_url text check (
    char_length(map_url) <= 2000 and
    map_url ~ '^https://(map[.]kakao[.]com|place[.]map[.]kakao[.]com|map[.]naver[.]com|naver[.]me)(/|$)'
  ),
  coordinate_source text check (coordinate_source in ('JUSO', 'HOST_PROVIDED', 'LICENSED')),
  source_reference text check (char_length(btrim(source_reference)) between 1 and 1000),
  is_confirmed boolean not null default false,
  confirmed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint lc_places_coordinate_pair check ((latitude is null) = (longitude is null)),
  constraint lc_places_coordinate_source check (
    latitude is null or (coordinate_source is not null and source_reference is not null)
  ),
  constraint lc_places_confirmation check (
    (not is_confirmed and confirmed_at is null)
    or (is_confirmed and confirmed_at is not null and road_address is not null)
  ),
  -- 본인 호스트의 여러 체험에서 재사용. 다른 호스트 장소의 무단 연결은 차단.
  constraint lc_places_id_owner_key unique (place_id, owner_host_id)
);

