begin;
set local lock_timeout = '5s';
set local statement_timeout = '30s';

create table public.lc_applications (
  application_id bigint generated by default as identity primary key,
  receipt_code text not null unique,
  auth_user_id uuid references auth.users(id) on delete set null,
  session_id bigint not null references public.lc_sessions(session_id) on delete restrict,
  applicant_name text not null check (char_length(btrim(applicant_name)) between 1 and 80),
  applicant_email text not null check (char_length(applicant_email) between 3 and 254),
  applicant_phone text check (applicant_phone is null or char_length(applicant_phone) <= 40),
  contact_language text not null check (contact_language in ('ko', 'en', 'ja')),
  attendee_count integer not null check (attendee_count >= 1),
  note text check (note is null or char_length(note) <= 1000),
  privacy_notice_version text not null check (char_length(privacy_notice_version) between 1 and 40),
  privacy_consented_at timestamptz not null,
  status text not null default 'PENDING' check (status in ('PENDING')),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  constraint lc_applications_expiry_after_creation check (expires_at > created_at)
);

create index lc_applications_session_expiry_idx
  on public.lc_applications(session_id, expires_at)
  where status = 'PENDING';
create index lc_applications_auth_user_idx
  on public.lc_applications(auth_user_id, created_at desc)
  where auth_user_id is not null;

create table public.lc_application_payments (
  payment_id bigint generated by default as identity primary key,
  application_id bigint not null unique
    references public.lc_applications(application_id) on delete restrict,
  payment_method text not null check (payment_method = 'DEMO_VIRTUAL_ACCOUNT'),
  amount bigint not null check (amount >= 0),
  status text not null default 'DEMO_ONLY' check (status = 'DEMO_ONLY'),
  demo_reference text not null unique check (demo_reference ~ '^DEMO-[A-F0-9]{32}$'),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null
);

create index lc_application_payments_expiry_idx
  on public.lc_application_payments(expires_at);

alter table public.lc_applications enable row level security;
alter table public.lc_application_payments enable row level security;

revoke all on public.lc_applications, public.lc_application_payments
  from public, anon, authenticated;
grant select on public.lc_applications, public.lc_application_payments to authenticated;

create policy lc_applications_read_own
  on public.lc_applications for select to authenticated
  using (auth_user_id = (select auth.uid()));

create policy lc_applications_host_read_owned_experience
  on public.lc_applications for select to authenticated
  using (
    exists (
      select 1
      from public.lc_sessions s
      where s.session_id = lc_applications.session_id
        and lc_private.lc_owns_experience(s.experience_id)
    )
  );

create policy lc_applications_admin_read
  on public.lc_applications for select to authenticated
  using (lc_private.lc_has_role('ADMIN'));

create policy lc_application_payments_read_own
  on public.lc_application_payments for select to authenticated
  using (
    exists (
      select 1 from public.lc_applications a
      where a.application_id = lc_application_payments.application_id
        and a.auth_user_id = (select auth.uid())
    )
  );

create policy lc_application_payments_admin_read
  on public.lc_application_payments for select to authenticated
  using (lc_private.lc_has_role('ADMIN'));

create function public.lc_submit_experience_application(
  p_session_id bigint,
  p_name text,
  p_email text,
  p_phone text,
  p_contact_language text,
  p_attendee_count integer,
  p_note text,
  p_privacy_notice_version text,
  p_privacy_consent boolean
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_auth_user_id uuid := auth.uid();
  v_session public.lc_sessions%rowtype;
  v_experience_title text;
  v_reserved_count numeric;
  v_total_amount bigint;
  v_receipt_code text;
  v_demo_reference text;
  v_application_id bigint;
  v_created_at timestamptz := now();
  v_expires_at timestamptz := now() + interval '24 hours';
begin
  if p_privacy_consent is distinct from true then
    raise exception using errcode = 'P0001', message = 'CONSENT_REQUIRED';
  end if;
  if p_session_id is null
    or p_name is null or char_length(btrim(p_name)) not between 1 and 80
    or p_email is null or char_length(btrim(p_email)) not between 3 and 254
    or btrim(p_email) !~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'
    or (p_phone is not null and char_length(btrim(p_phone)) > 40)
    or p_contact_language is null or p_contact_language not in ('ko', 'en', 'ja')
    or p_attendee_count is null or p_attendee_count < 1
    or (p_note is not null and char_length(p_note) > 1000)
    or p_privacy_notice_version is null
    or char_length(btrim(p_privacy_notice_version)) not between 1 and 40 then
    raise exception using errcode = 'P0001', message = 'INVALID_APPLICATION';
  end if;

  select s.*
    into v_session
  from public.lc_sessions s
  where s.session_id = p_session_id
  for update of s;

  if not found then
    raise exception using errcode = 'P0001', message = 'APPLICATION_CLOSED';
  end if;
  select e.title into v_experience_title
  from public.lc_experiences e
  where e.experience_id = v_session.experience_id;
  if v_session.status <> 'RECRUITING'
    or v_session.starts_at <= v_created_at
    or (v_session.recruit_deadline is not null and v_session.recruit_deadline <= v_created_at)
    or not lc_private.lc_is_public_experience(v_session.experience_id) then
    raise exception using errcode = 'P0001', message = 'APPLICATION_CLOSED';
  end if;
  if v_session.fee_amount < 0 or v_session.capacity < 1 then
    raise exception using errcode = 'P0001', message = 'INVALID_SESSION';
  end if;

  select coalesce(sum(a.attendee_count), 0)
    into v_reserved_count
  from public.lc_applications a
  where a.session_id = p_session_id
    and a.status = 'PENDING'
    and a.expires_at > v_created_at;

  if v_reserved_count + p_attendee_count > v_session.capacity then
    raise exception using errcode = 'P0001', message = 'SESSION_FULL';
  end if;

  v_total_amount := v_session.fee_amount::bigint * p_attendee_count::bigint;
  v_receipt_code := 'LE-' || replace(gen_random_uuid()::text, '-', '');
  v_demo_reference := 'DEMO-' || upper(replace(gen_random_uuid()::text, '-', ''));

  insert into public.lc_applications (
    receipt_code, auth_user_id, session_id, applicant_name, applicant_email,
    applicant_phone, contact_language, attendee_count, note,
    privacy_notice_version, privacy_consented_at, status, created_at, expires_at
  ) values (
    v_receipt_code, v_auth_user_id, p_session_id, btrim(p_name), lower(btrim(p_email)),
    nullif(btrim(coalesce(p_phone, '')), ''), p_contact_language, p_attendee_count,
    nullif(btrim(coalesce(p_note, '')), ''), btrim(p_privacy_notice_version),
    v_created_at, 'PENDING', v_created_at, v_expires_at
  ) returning application_id into v_application_id;

  insert into public.lc_application_payments (
    application_id, payment_method, amount, status, demo_reference, created_at, expires_at
  ) values (
    v_application_id, 'DEMO_VIRTUAL_ACCOUNT', v_total_amount,
    'DEMO_ONLY', v_demo_reference, v_created_at, v_expires_at
  );

  return jsonb_build_object(
    'application_id', v_application_id,
    'receipt_code', v_receipt_code,
    'session_id', p_session_id,
    'experience_title', v_experience_title,
    'starts_at', v_session.starts_at,
    'ends_at', v_session.ends_at,
    'attendee_count', p_attendee_count,
    'unit_fee_amount', v_session.fee_amount,
    'total_amount', v_total_amount,
    'payment_status', 'DEMO_ONLY',
    'demo_reference', v_demo_reference,
    'expires_at', v_expires_at
  );
end;
$$;

revoke all on function public.lc_submit_experience_application(
  bigint, text, text, text, text, integer, text, text, boolean
) from public;
grant execute on function public.lc_submit_experience_application(
  bigint, text, text, text, text, integer, text, text, boolean
) to anon, authenticated;

comment on table public.lc_applications is
  '로컬이음 참가 신청. PENDING 시연 신청은 접수 후 24시간 동안 정원에 포함된다.';
comment on table public.lc_application_payments is
  '실제 입금이 불가능한 시연 결제 참조만 저장한다. 실제 계좌번호나 결제 상태는 저장하지 않는다.';
comment on function public.lc_submit_experience_application(
  bigint, text, text, text, text, integer, text, text, boolean
) is '신청 및 DEMO_ONLY 결제를 원자적으로 생성한다. 실제 예약·결제 확정 기능은 없다.';

commit;
