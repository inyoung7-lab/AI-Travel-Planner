-- LOCAL EUM / 여행, 한걸음 — 최초 스키마 마이그레이션
-- 검토 완료. 실제 적용은 사용자가 Dashboard에서 프로젝트 ID를 확인한 뒤 SQL Editor에서 수행한다.
-- 승인된 프로젝트: local-eum-dev / rhkaxmqdkztpbljkunxb
-- 이 파일은 lc_private 및 다섯 lc_ 테이블만 추가하며 기존 객체를 삭제하거나 초기화하지 않는다.
-- 테스트 계정/시연 행은 seed_demo.sql에서 별도로 추가한다.

begin;

-- 정책 보조 함수는 Supabase Data API에 노출하지 않는 스키마에 둔다.
create schema lc_private;

create table public.lc_user_roles (
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null check (role in ('HOST', 'ADMIN')),
  assigned_at timestamptz not null default now(),
  assigned_by uuid references auth.users(id) on delete set null,
  primary key (user_id, role)
);

create table public.lc_hosts (
  host_id bigint generated by default as identity primary key,
  auth_user_id uuid unique references auth.users(id) on delete restrict,
  display_name text not null check (char_length(btrim(display_name)) between 1 and 80),
  bio text,
  page_slug text unique check (page_slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  approval_status text not null default 'PENDING'
    check (approval_status in ('PENDING', 'APPROVED', 'SUSPENDED')),
  is_public boolean not null default false,
  created_at timestamptz not null default now(),
  constraint lc_hosts_approved_has_auth check
    (approval_status <> 'APPROVED' or auth_user_id is not null),
  constraint lc_hosts_public_is_approved check
    (not is_public or approval_status = 'APPROVED')
);

create table public.lc_program_templates (
  template_id bigint generated by default as identity primary key,
  title text not null check (char_length(btrim(title)) between 1 and 120),
  description text,
  duration_min integer not null check (duration_min between 1 and 1440),
  default_fee_amount integer not null default 0 check (default_fee_amount >= 0),
  is_active boolean not null default false,
  created_at timestamptz not null default now()
);

create table public.lc_experiences (
  experience_id bigint generated by default as identity primary key,
  host_id bigint not null references public.lc_hosts(host_id) on delete restrict,
  template_id bigint not null references public.lc_program_templates(template_id) on delete restrict,
  title text not null check (char_length(btrim(title)) between 1 and 120),
  description text,
  region_code text,
  status text not null default 'DRAFT' check (status in ('DRAFT', 'PUBLISHED')),
  created_at timestamptz not null default now()
);

create table public.lc_sessions (
  session_id bigint generated by default as identity primary key,
  experience_id bigint not null references public.lc_experiences(experience_id) on delete restrict,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  meeting_place text not null check (char_length(btrim(meeting_place)) between 1 and 200),
  recruit_deadline timestamptz,
  min_people integer not null check (min_people >= 1),
  capacity integer not null,
  fee_amount integer not null default 0 check (fee_amount >= 0),
  status text not null default 'DRAFT' check (status in ('DRAFT', 'RECRUITING')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint lc_sessions_time_order check (ends_at > starts_at),
  constraint lc_sessions_capacity check (capacity >= min_people),
  constraint lc_sessions_deadline check (recruit_deadline is null or recruit_deadline <= starts_at)
);

create index lc_experiences_host_idx on public.lc_experiences(host_id);
create index lc_experiences_template_idx on public.lc_experiences(template_id);
create index lc_sessions_experience_start_idx on public.lc_sessions(experience_id, starts_at);

-- 역할 부여는 신뢰할 수 있는 ADMIN 서버 흐름에서만 수행한다.
-- 이 함수들은 마이그레이션 소유자(postgres)가 만들고 호출자의 RLS를 우회해
-- 역할/소유권을 확인한다. lc_private를 API 노출 스키마에 추가하지 않는다.
create function lc_private.lc_has_role(_role text)
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.lc_user_roles r
    where r.user_id = (select auth.uid()) and r.role = _role
  );
$$;

create function lc_private.lc_owns_host(_host_id bigint)
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.lc_hosts h
    where h.host_id = _host_id
      and h.auth_user_id = (select auth.uid())
      and lc_private.lc_has_role('HOST')
  );
$$;

create function lc_private.lc_owns_experience(_experience_id bigint)
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1
    from public.lc_experiences e
    join public.lc_hosts h on h.host_id = e.host_id
    where e.experience_id = _experience_id
      and h.auth_user_id = (select auth.uid())
      and h.approval_status = 'APPROVED'
      and lc_private.lc_has_role('HOST')
  );
$$;

create function lc_private.lc_is_public_experience(_experience_id bigint)
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1
    from public.lc_experiences e
    join public.lc_hosts h on h.host_id = e.host_id
    join public.lc_program_templates t on t.template_id = e.template_id
    where e.experience_id = _experience_id
      and e.status = 'PUBLISHED'
      and h.approval_status = 'APPROVED'
      and h.is_public
      and t.is_active
  );
$$;

create function lc_private.lc_touch_updated_at()
returns trigger language plpgsql set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create trigger lc_sessions_touch_updated_at
before update on public.lc_sessions
for each row execute function lc_private.lc_touch_updated_at();

-- PUBLIC 기본 함수 실행 권한을 제거하고, 정책 평가에 필요한 호출만 허용한다.
revoke all on schema lc_private from public;
grant usage on schema lc_private to anon, authenticated;
revoke all on function lc_private.lc_has_role(text) from public;
revoke all on function lc_private.lc_owns_host(bigint) from public;
revoke all on function lc_private.lc_owns_experience(bigint) from public;
revoke all on function lc_private.lc_is_public_experience(bigint) from public;
revoke all on function lc_private.lc_touch_updated_at() from public;
grant execute on function lc_private.lc_has_role(text) to authenticated;
grant execute on function lc_private.lc_owns_host(bigint) to authenticated;
grant execute on function lc_private.lc_owns_experience(bigint) to authenticated;
grant execute on function lc_private.lc_is_public_experience(bigint) to anon, authenticated;

alter table public.lc_user_roles enable row level security;
alter table public.lc_hosts enable row level security;
alter table public.lc_program_templates enable row level security;
alter table public.lc_experiences enable row level security;
alter table public.lc_sessions enable row level security;

-- 팀의 다른 public 테이블은 건드리지 않고 이 다섯 테이블의 API 권한만 설정한다.
revoke all on public.lc_user_roles, public.lc_hosts,
  public.lc_program_templates, public.lc_experiences, public.lc_sessions
  from public, anon, authenticated;

grant select on public.lc_user_roles to authenticated;
grant select (host_id, display_name, bio, page_slug)
  on public.lc_hosts to anon, authenticated;
grant select (approval_status, is_public)
  on public.lc_hosts to authenticated;
grant select on public.lc_program_templates, public.lc_experiences, public.lc_sessions
  to anon, authenticated;
grant update (starts_at, ends_at, meeting_place, recruit_deadline,
  min_people, capacity, fee_amount, status)
  on public.lc_sessions to authenticated;

create policy lc_roles_read_self_or_admin on public.lc_user_roles
for select to authenticated
using (user_id = (select auth.uid()) or (select lc_private.lc_has_role('ADMIN')));

create policy lc_hosts_read_public on public.lc_hosts
for select to anon, authenticated
using (approval_status = 'APPROVED' and is_public);
create policy lc_hosts_read_self_or_admin on public.lc_hosts
for select to authenticated
using (
  lc_private.lc_owns_host(host_id)
  or (select lc_private.lc_has_role('ADMIN'))
);

create policy lc_templates_read_active on public.lc_program_templates
for select to anon, authenticated using (is_active);
create policy lc_templates_read_admin on public.lc_program_templates
for select to authenticated using ((select lc_private.lc_has_role('ADMIN')));

create policy lc_experiences_read_public on public.lc_experiences
for select to anon, authenticated
using (lc_private.lc_is_public_experience(experience_id));
create policy lc_experiences_read_owner_or_admin on public.lc_experiences
for select to authenticated
using (
  lc_private.lc_owns_experience(experience_id)
  or (select lc_private.lc_has_role('ADMIN'))
);

create policy lc_sessions_read_public on public.lc_sessions
for select to anon, authenticated
using (status = 'RECRUITING' and lc_private.lc_is_public_experience(experience_id));
create policy lc_sessions_read_owner_or_admin on public.lc_sessions
for select to authenticated
using (
  lc_private.lc_owns_experience(experience_id)
  or (select lc_private.lc_has_role('ADMIN'))
);
create policy lc_sessions_update_owner_or_admin on public.lc_sessions
for update to authenticated
using (
  lc_private.lc_owns_experience(experience_id)
  or (select lc_private.lc_has_role('ADMIN'))
)
with check (
  (
    lc_private.lc_owns_experience(experience_id)
    or (select lc_private.lc_has_role('ADMIN'))
  )
  and (status = 'DRAFT' or lc_private.lc_is_public_experience(experience_id))
);

-- INSERT/DELETE 및 역할·호스트·프로그램·체험의 클라이언트 쓰기 권한은 없다.
-- 비회원 신청 테이블과 보호된 신청 API는 다음 단계에서 별도 설계·검증한다.
commit;
