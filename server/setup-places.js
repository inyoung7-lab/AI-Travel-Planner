// 수민 담당: 커뮤니티 장소 테이블 만들기 (한 번만 실행해요)
// 실행: node server/setup-places.js
// 글에 태그한 장소(이름·주소·지역)를 저장해요. 예시 장소 8곳(1~8번)도 같이 넣어요.
import { getConnection } from "./db.js";

const c = await getConnection();
try {
  try {
    await c.execute(`CREATE TABLE COMM_PLACE (
      place_id   NUMBER(30) GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
      name       VARCHAR2(200 CHAR) NOT NULL,
      address    VARCHAR2(300 CHAR),
      region     VARCHAR2(20 CHAR),
      lat        NUMBER(10,6),
      lng        NUMBER(10,6),
      ext_key    VARCHAR2(100),
      created_at DATE DEFAULT SYSDATE NOT NULL,
      CONSTRAINT comm_place_ext_uq UNIQUE (ext_key)
    )`);
    console.log("✅ 만들었어요: COMM_PLACE");
  } catch (e) {
    if (e.message.includes("ORA-00955")) console.log("이미 있어요: COMM_PLACE");
    else throw e;
  }
  // 글에 태그한 장소마다 남기는 별점(선택) 칸
  try {
    await c.execute("ALTER TABLE COMM_POST_PLACE ADD (rating NUMBER(1))");
    console.log("✅ 장소별 별점 칸을 추가했어요: COMM_POST_PLACE.rating");
  } catch (e) {
    if (e.message.includes("ORA-01430")) console.log("이미 있어요: COMM_POST_PLACE.rating");
    else throw e;
  }
  const samples = [
    [1, "제주 애월", "제주특별자치도 제주시 애월읍", "제주"],
    [2, "제주 협재해변", "제주특별자치도 제주시 한림읍 협재리", "제주"],
    [3, "여수 해양케이블카", "전남 여수시 돌산읍 돌산로", "전남"],
    [4, "여수 오동도", "전남 여수시 수정동 오동도", "전남"],
    [5, "순천만 국가정원", "전남 순천시 국가정원1호길", "전남"],
    [6, "순천 낙안읍성", "전남 순천시 낙안면", "전남"],
    [7, "부산 흰여울문화마을", "부산 영도구 흰여울길", "부산"],
    [8, "서울 성수동", "서울 성동구 성수동", "서울"],
  ];
  for (const [id, name, address, region] of samples) {
    const r = await c.execute("SELECT COUNT(*) AS n FROM COMM_PLACE WHERE place_id = :id", { id });
    if (r.rows[0][0] === 0) {
      await c.execute(
        "INSERT INTO COMM_PLACE (place_id, name, address, region, ext_key) VALUES (:id, :name, :address, :region, :k)",
        { id, name, address, region, k: "sample:" + id }
      );
    }
  }
  await c.commit();
  console.log("✅ 예시 장소 8곳 확인 완료");
} catch (e) {
  console.log("❌ 오류:", e.message.split("\n")[0]);
} finally {
  await c.close();
}
