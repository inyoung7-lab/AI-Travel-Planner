import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
const owner = '00000000-0000-0000-0000-000000000001';
const other = '00000000-0000-0000-0000-000000000002';

test('Supabase migration: auth profiles, transactions, RLS, likes, wishes and travel data', async () => {
 const db = new PGlite();
 try {
 await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;create schema auth;
 alter default privileges in schema public grant all on tables to anon,authenticated;
 create table auth.users(id uuid primary key,email text,raw_user_meta_data jsonb);
 create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
 grant usage on schema auth to anon,authenticated;grant execute on function auth.uid() to anon,authenticated;
 insert into auth.users values('${owner}','one@example.com','{"name":"여행자"}');`);
 await db.exec(await readFile(new URL('../supabase/migrations/202610250001_travel_supabase.sql',import.meta.url),'utf8'));
 await db.exec(await readFile(new URL('../supabase/migrations/202610250002_cloud_itineraries.sql',import.meta.url),'utf8'));
 await db.exec(`insert into auth.users values('${other}','two@example.com','{"name":"다른 회원"}');
 insert into public.comm_place(name,ext_key,region) values('서울숲','sample:1001','서울'),('경복궁','tourapi:123','서울'),('박물관','tourapi:456','서울');
 insert into public.mytrip_plan(user_id,title,region,start_date,end_date) values('${owner}','내 여행','서울','2026-10-20','2026-10-21');`);
 const asUser = async (id, sql) => {
   await db.exec(`reset role;set role authenticated;select set_config('request.jwt.claim.sub','${id}',false);`);
   return db.query(sql);
 };
 const result = await asUser(owner, `select public.travel_create_post('리뷰','여행 리뷰','좋은 여행','본문','서울',array[1001::bigint],'{"1001":5}') id`);
 const post = result.rows[0].id;
 assert.equal((await db.query('select user_name from public.travel_profiles order by user_id')).rows[0].user_name,'여행자');
 assert.equal((await asUser(other, `select public.travel_toggle_like('post',${post}) value`)).rows[0].value.likes,1);
 assert.equal((await db.query(`select like_count from public.comm_post where post_id=${post}`)).rows[0].like_count,1);
 assert.equal((await asUser(other, `select public.travel_toggle_like('post',${post}) value`)).rows[0].value.likes,0);
 assert.equal((await asUser(owner, 'select public.travel_toggle_wish(1001) wished')).rows[0].wished,true);
 assert.equal((await asUser(other, 'select * from public.mytrip_wish')).rows.length,0);
 assert.equal((await asUser(other, 'select * from public.mytrip_plan')).rows.length,0);
 await assert.rejects(asUser(other,'select public.travel_add_trip_place(1,1001)'),/no_data_found/);
 await asUser(owner,'select public.travel_add_trip_place(1,1001)');
 await assert.rejects(asUser(owner,'select public.travel_add_trip_place(1,1001)'),/unique/);
 await assert.rejects(asUser(other,`insert into public.comm_post(user_id,category,title,content) values('${owner}','소통','위조','본문')`),/row-level security/);
 await assert.rejects(asUser(other,`insert into public.comm_post(user_id,category,title,content,like_count) values('${other}','소통','조작','본문',500)`),/permission denied/);
 await assert.rejects(asUser(other,`update public.comm_post set like_count=100 where post_id=${post}`),/permission denied/);
 assert.equal((await asUser(other,`delete from public.comm_post where post_id=${post} returning post_id`)).rows.length,0);
 const comment = (await asUser(other,`insert into public.comm_comment(user_id,post_id,content) values('${other}',${post},'댓글') returning comment_id`)).rows[0].comment_id;
 assert.equal((await asUser(owner,`select public.travel_toggle_like('comment',${comment}) value`)).rows[0].value.likes,1);
 await assert.rejects(asUser(owner,`insert into public.comm_comment(user_id,post_id,parent_id,content) values('${owner}',${post},999,'잘못된 답글')`),/Invalid comment parent/);
 const savedPayload=JSON.stringify({title:'여행',days:[{day:1,items:[]}]});
 await asUser(owner,`select public.travel_save_itinerary('plan-a','${savedPayload}'::jsonb)`);
 await asUser(owner,`select public.travel_save_itinerary('plan-b','${savedPayload}'::jsonb)`);
 assert.equal((await db.query('select count(*)::int n from public.travel_itineraries where is_current')).rows[0].n,1);
 await asUser(owner,"select public.travel_open_itinerary('plan-a')");
 assert.equal((await db.query('select client_id from public.travel_itineraries where is_current')).rows[0].client_id,'plan-a');
 assert.equal((await asUser(other,'select * from public.travel_itineraries')).rows.length,0);
 await assert.rejects(asUser(other,"select public.travel_open_itinerary('plan-a')"),/no_data_found/);
 await assert.rejects(asUser(owner,"select public.travel_save_itinerary('bad','{}'::jsonb)"),/check constraint/);
 await asUser(owner,`select public.travel_import_itineraries('[{"savedId":"imported","title":"이전 일정","days":[{"day":1,"items":[]}]}]'::jsonb,'imported')`);
 await asUser(owner,`select public.travel_import_itineraries('[{"savedId":"imported","title":"이전 일정","days":[{"day":1,"items":[]}]}]'::jsonb,'imported')`);
 assert.equal((await db.query('select count(*)::int n from public.travel_itineraries')).rows[0].n,3);
 assert.equal((await db.query('select client_id from public.travel_itineraries where is_current')).rows[0].client_id,'plan-a');
 await db.exec("reset role;set role anon;select set_config('request.jwt.claim.sub','',false)");
 assert.equal((await db.query('select * from public.community_posts')).rows.length,1);
 assert.equal((await db.query('select public.travel_itinerary_regions() regions')).rows[0].regions[0],'서울');
 await assert.rejects(db.query('select public.travel_toggle_wish(1001)'),/permission denied/);
 await assert.rejects(db.query('select * from public.travel_search_log'),/permission denied/);
 await db.query(`select public.travel_view_post(${post})`);
 assert.equal((await db.query('select public.travel_post_counts() counts')).rows[0].counts.review,1);
 assert.equal((await db.query("select public.travel_search_places('서울숲') places")).rows[0].places[0].id,1001);
 await asUser(owner,`delete from public.comm_post where post_id=${post}`);
 assert.equal((await db.query('select * from public.comm_comment')).rows.length,0);
 } finally { await db.close(); }
});
