-- 수민 담당: 나의 여행(MYTRIP_) · 커뮤니티(COMM_) 테이블
-- 회원은 로그인 담당분의 MEMBER(USER_ID)를, 여행지는 기존 PLACE(PLACE_ID)를 연결만 합니다. (PLACE 컬럼명은 팀 DB와 확인 필요)

CREATE TABLE MYTRIP_PLAN (
  trip_id     NUMBER GENERATED AS IDENTITY PRIMARY KEY,
  user_id     VARCHAR2(50)  NOT NULL REFERENCES MEMBER(USER_ID),
  title       VARCHAR2(100) NOT NULL,
  region      VARCHAR2(20)  NOT NULL,
  start_date  DATE NOT NULL,
  end_date    DATE NOT NULL,
  created_at  DATE DEFAULT SYSDATE NOT NULL
);
CREATE TABLE MYTRIP_PLACE (
  tp_id    NUMBER GENERATED AS IDENTITY PRIMARY KEY,
  trip_id  NUMBER NOT NULL REFERENCES MYTRIP_PLAN(trip_id) ON DELETE CASCADE,
  place_id NUMBER NOT NULL,
  day_no   NUMBER,
  memo     VARCHAR2(200)
);
CREATE TABLE MYTRIP_WISH (
  wish_id    NUMBER GENERATED AS IDENTITY PRIMARY KEY,
  user_id    VARCHAR2(50) NOT NULL REFERENCES MEMBER(USER_ID),
  place_id   NUMBER NOT NULL,
  created_at DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT mytrip_wish_uq UNIQUE (user_id, place_id)
);

CREATE TABLE COMM_POST (
  post_id      NUMBER GENERATED AS IDENTITY PRIMARY KEY,
  user_id      VARCHAR2(50)  NOT NULL REFERENCES MEMBER(USER_ID),
  category     VARCHAR2(10)  NOT NULL CHECK (category IN ('리뷰','질문','소통')),
  sub_category VARCHAR2(10)  CHECK (sub_category IN ('여행 리뷰','장소 리뷰')),
  title        VARCHAR2(100) NOT NULL,
  content      CLOB NOT NULL,
  region       VARCHAR2(20),
  rating       NUMBER(1) CHECK (rating BETWEEN 1 AND 5),
  created_at   DATE DEFAULT SYSDATE NOT NULL,
  view_count   NUMBER DEFAULT 0 NOT NULL,
  like_count   NUMBER DEFAULT 0 NOT NULL
);
CREATE TABLE COMM_POST_PLACE (
  pp_id    NUMBER GENERATED AS IDENTITY PRIMARY KEY,
  post_id  NUMBER NOT NULL REFERENCES COMM_POST(post_id) ON DELETE CASCADE,
  place_id NUMBER NOT NULL
);
CREATE TABLE COMM_POST_IMAGE (
  img_id    NUMBER GENERATED AS IDENTITY PRIMARY KEY,
  post_id   NUMBER NOT NULL REFERENCES COMM_POST(post_id) ON DELETE CASCADE,
  image_url VARCHAR2(300) NOT NULL,
  sort_no   NUMBER NOT NULL
);
CREATE TABLE COMM_COMMENT (
  comment_id NUMBER GENERATED AS IDENTITY PRIMARY KEY,
  post_id    NUMBER NOT NULL REFERENCES COMM_POST(post_id) ON DELETE CASCADE,
  user_id    VARCHAR2(50) NOT NULL REFERENCES MEMBER(USER_ID),
  parent_id  NUMBER REFERENCES COMM_COMMENT(comment_id) ON DELETE CASCADE,
  content    VARCHAR2(1000) NOT NULL,
  created_at DATE DEFAULT SYSDATE NOT NULL,
  like_count NUMBER DEFAULT 0 NOT NULL
);
CREATE TABLE COMM_POST_LIKE (
  like_id NUMBER GENERATED AS IDENTITY PRIMARY KEY,
  post_id NUMBER NOT NULL REFERENCES COMM_POST(post_id) ON DELETE CASCADE,
  user_id VARCHAR2(50) NOT NULL REFERENCES MEMBER(USER_ID),
  CONSTRAINT comm_post_like_uq UNIQUE (post_id, user_id)
);
CREATE TABLE COMM_COMMENT_LIKE (
  cl_id      NUMBER GENERATED AS IDENTITY PRIMARY KEY,
  comment_id NUMBER NOT NULL REFERENCES COMM_COMMENT(comment_id) ON DELETE CASCADE,
  user_id    VARCHAR2(50) NOT NULL REFERENCES MEMBER(USER_ID),
  CONSTRAINT comm_comment_like_uq UNIQUE (comment_id, user_id)
);
